/// <summary>
/// ULG8 to ULG11, ULG13, ULG42 (errata G52, R11.71): the event store throws <see cref="LogUnreadableException"/> around the driver's exception for a fault of
/// the store, the caller's cancellation stays the caller's, the three gates answer a fault wrapped inside another exception as they answer a bare one, and the
/// private flag store classifies by the one predicate. Every fault is a real one in a throwaway database: a grant revoked from the application role on a
/// schema of its own (and granted back in a <c>finally</c>) and a pool of one connection held by the test. No fact asserts how fast anything is answered.
/// </summary>
[SuppressMessage(
    "Design",
    "CA1515:Consider making public types internal",
    Justification = "xUnit discovery needs the class public.")]
[SuppressMessage(
    "Naming",
    "CA1707:Identifiers should not contain underscores",
    Justification = "Test names carry the requirement IDs they enforce verbatim.")]
[Collection(PostgresCollectionDefinition.Name)]
public sealed class StoreFaultInfrastructureTests(PostgresDatabaseFixture fixture) : IAsyncDisposable
{
    private readonly List<IAsyncDisposable> _cleanup = [];

    private static CancellationToken Ct => TestContext.Current.CancellationToken;

    private static T Require<T>(Result<T> result) =>
        result.Match(v => v, e => throw new InvalidOperationException($"{e.Type}: {e.Title} ({e.Detail})"));

    public async ValueTask DisposeAsync()
    {
        foreach (var owned in _cleanup) await owned.DisposeAsync();
        GC.SuppressFinalize(this);
    }

    private NpgsqlDataSource StarvedSource()
    {
        var builder = new NpgsqlConnectionStringBuilder(fixture.AppRoleConnectionString) { MaxPoolSize = 1, MinPoolSize = 0, Timeout = 1, Pooling = true };
        var source = NpgsqlDataSource.Create(builder.ConnectionString);
        _cleanup.Add(source);
        return source;
    }

    private PostgresEventStore StoreOn(NpgsqlDataSource source, string schema) =>
        new(source, TimeProvider.System, fixture.PermissiveLifecycleGateFor(fixture.AppRoleDataSource), schema);

    [SuppressMessage("Security", "CA2100:Review SQL queries for security vulnerabilities", Justification = "The schema is generated by the fixture from a literal prefix and a GUID; the role is the connection's own current_user.")]
    private async Task AdminAsync(string sql)
    {
        await using var connection = await fixture.AdminDataSource.OpenConnectionAsync(Ct);
        await using var command = new NpgsqlCommand(sql, connection);
        await command.ExecuteNonQueryAsync(Ct);
    }

    private async Task<string> RoleAsync()
    {
        await using var connection = await fixture.AppRoleDataSource.OpenConnectionAsync(Ct);
        await using var command = new NpgsqlCommand("SELECT current_user;", connection);
        return (string)(await command.ExecuteScalarAsync(Ct))!;
    }

    /// <summary>What a read does, as a sentence: the exception's type name, or the word for a result.</summary>
    [SuppressMessage("Design", "CA1031:Do not catch general exception types", Justification = "The fact reports whatever type the read threw.")]
    private static async Task<(string Outcome, Exception? Thrown)> OutcomeAsync(Func<Task<Result<IReadOnlyList<AppendedEvent>>>> read)
    {
        try
        {
            var result = await read();
            return (result.TryGetValue(out _, out var error) ? "a result" : $"a failed result {error!.Type}", null);
        }
        catch (Exception e) when (!Ct.IsCancellationRequested)
        {
            return (e.GetType().Name, e);
        }
    }

    private static bool Contains(Exception? exception, Func<Exception, bool> predicate)
    {
        for (var e = exception; e is not null; e = e.InnerException)
            if (predicate(e)) return true;

        return false;
    }

    /// <summary>
    /// ULG8. <c>SELECT</c> revoked from the application role on the log: both reads throw <see cref="LogUnreadableException"/> with the driver's
    /// <see cref="PostgresException"/> (42501) inside, and the exception's <c>Cause</c> names the SQLSTATE and not the message.
    /// </summary>
    [Theory]
    [InlineData("ReadByAggregateAsync")]
    [InlineData("ReadForwardAsync")]
    public async Task R11_71_ULG8_ARevokedSelectIsALogUnreadableExceptionAroundTheDriversException(string read)
    {
        var schema = await fixture.CreateIsolatedSchemaAsync(Ct);
        var role = await RoleAsync();
        var store = StoreOn(fixture.AppRoleDataSource, schema);
        var aggregate = Require(AggregateId.Create("ulg8"));

        (string Outcome, Exception? Thrown) outcome;
        try
        {
            await AdminAsync($"REVOKE SELECT ON \"{schema}\".events FROM \"{role}\";");
            outcome = read == "ReadByAggregateAsync"
                ? await OutcomeAsync(() => store.ReadByAggregateAsync(aggregate, Ct))
                : await OutcomeAsync(() => store.ReadForwardAsync(EventSequence.Zero, null, Ct));
        }
        finally
        {
            await AdminAsync($"GRANT SELECT ON \"{schema}\".events TO \"{role}\";");
        }

        var problems = new List<string>();
        if (outcome.Thrown is not LogUnreadableException logged)
        {
            problems.Add($"expected LogUnreadableException, actual {outcome.Outcome}");
        }
        else
        {
            if (!Contains(logged, e => e is PostgresException { SqlState: "42501" })) problems.Add("no PostgresException 42501 inside the log's exception");
            if (!logged.Cause.Contains("42501", StringComparison.Ordinal)) problems.Add($"the Cause \"{logged.Cause}\" does not name the SQLSTATE");
            if (logged.Cause.Contains("permission denied", StringComparison.OrdinalIgnoreCase)) problems.Add("the Cause carries the driver's message");
        }

        Assert.True(problems.Count == 0, $"{read}: " + string.Join("; ", problems));
    }

    /// <summary>ULG9. A starved pool (one connection, held by the test, a one-second timeout): <see cref="LogUnreadableException"/> around the pool's exception.</summary>
    [Theory]
    [InlineData("ReadByAggregateAsync")]
    [InlineData("ReadForwardAsync")]
    public async Task R11_71_ULG9_AStarvedPoolIsALogUnreadableException(string read)
    {
        var schema = await fixture.CreateIsolatedSchemaAsync(Ct);
        var starved = StarvedSource();
        await using var occupant = await starved.OpenConnectionAsync(Ct);
        var store = StoreOn(starved, schema);
        var aggregate = Require(AggregateId.Create("ulg9"));

        var outcome = read == "ReadByAggregateAsync"
            ? await OutcomeAsync(() => store.ReadByAggregateAsync(aggregate, Ct))
            : await OutcomeAsync(() => store.ReadForwardAsync(EventSequence.Zero, null, Ct));

        var problems = new List<string>();
        if (outcome.Thrown is not LogUnreadableException logged)
        {
            problems.Add($"expected LogUnreadableException, actual {outcome.Outcome}");
        }
        else if (!Contains(logged, e => e is TimeoutException))
        {
            problems.Add("no TimeoutException inside the log's exception");
        }

        Assert.True(problems.Count == 0, $"{read}: " + string.Join("; ", problems));
    }

    /// <summary>ULG10, a control. The caller's cancelled token is the caller's <see cref="OperationCanceledException"/>, not a store fault.</summary>
    [Fact]
    public async Task R11_71_ULG10_TheCallersCancelledTokenIsNotAStoreFault()
    {
        var schema = await fixture.CreateIsolatedSchemaAsync(Ct);
        var store = StoreOn(fixture.AppRoleDataSource, schema);
        using var cancelled = CancellationTokenSource.CreateLinkedTokenSource(Ct);
        await cancelled.CancelAsync();

        var outcome = await OutcomeAsync(() => store.ReadForwardAsync(EventSequence.Zero, null, cancelled.Token));

        Assert.True(outcome.Thrown is OperationCanceledException, $"expected the caller's cancellation, actual {outcome.Outcome}");
    }

    /// <summary>ULG11, a control. A healthy store still reads: an empty aggregate is an empty list and not a failure (the contract suite is <c>PostgresEventStoreContractTests</c>).</summary>
    [Fact]
    public async Task R11_71_ULG11_AHealthyStoreReadsAnEmptyAggregateAsAnEmptyList()
    {
        var schema = await fixture.CreateIsolatedSchemaAsync(Ct);
        var store = StoreOn(fixture.AppRoleDataSource, schema);

        var read = Require(await store.ReadByAggregateAsync(Require(AggregateId.Create("ulg11")), Ct));

        Assert.True(read.Count == 0, $"expected an empty list, actual {read.Count} events");
    }

    // ----- ULG13: a driver fault wrapped inside another exception -----

    /// <summary>A clock whose timers fail with a driver fault wrapped in an <see cref="InvalidOperationException"/>: the shape of a fault seen through a layer.</summary>
    private sealed class WrappingClock : TimeProvider
    {
        public override ITimer CreateTimer(TimerCallback callback, object? state, TimeSpan dueTime, TimeSpan period) =>
            throw new InvalidOperationException("the timer failed", new NpgsqlException("connection lost", new TimeoutException("the operation has timed out")));
    }

    /// <summary>A logger that throws once, the first time Npgsql asks it to write: a wrapped driver fault from inside the driver's own code path.</summary>
    private sealed class ThrowingOnceLoggerFactory : ILoggerFactory
    {
        private int _armed;

        internal void Arm() => Volatile.Write(ref _armed, 1);

        public void AddProvider(ILoggerProvider provider)
        {
        }

        public ILogger CreateLogger(string categoryName) => new ThrowingOnce(this);

        public void Dispose()
        {
        }

        private sealed class ThrowingOnce(ThrowingOnceLoggerFactory owner) : ILogger
        {
            public IDisposable? BeginScope<TState>(TState state)
                where TState : notnull => null;

            public bool IsEnabled(LogLevel logLevel) => Volatile.Read(ref owner._armed) == 1;

            public void Log<TState>(LogLevel logLevel, Microsoft.Extensions.Logging.EventId eventId, TState state, Exception? exception, Func<TState, Exception?, string> formatter)
            {
                if (Interlocked.Exchange(ref owner._armed, 0) == 1)
                    throw new InvalidOperationException("the logger failed", new NpgsqlException("connection lost", new TimeoutException("the operation has timed out")));
            }
        }
    }

    private static string Outcome(Result<IAsyncDisposable> result) => result.TryGetValue(out _, out var error) ? "entered" : error!.Type;

    /// <summary>
    /// ULG13, the write gate. A driver fault seen inside an <see cref="InvalidOperationException"/> (the gate's own clock fails, after the connection and the
    /// transaction are open) is <c>gate-unavailable</c>, as a bare driver fault is. Today the gate's two direct <c>catch</c> clauses let it escape.
    /// </summary>
    [Fact]
    [SuppressMessage("Design", "CA1031:Do not catch general exception types", Justification = "The fact reports whatever escaped the gate.")]
    public async Task R11_71_ULG13_TheAgentWriteGateAnswersAWrappedDriverFaultAsGateUnavailable()
    {
        var gate = new PostgresAgentWriteGate(fixture.AppRoleDataSource, new WrappingClock(), TimeSpan.FromSeconds(5), 16, "gate_" + Guid.NewGuid().ToString("N"));
        string outcome;
        try
        {
            var result = await gate.EnterAsync(Typed.Agent("https://agents.example/ulg13"), Ct);
            if (result.TryGetValue(out var hold, out var error))
            {
                await hold!.DisposeAsync();
                outcome = "entered";
            }
            else
            {
                outcome = error!.Type;
            }
        }
        catch (Exception e) when (!Ct.IsCancellationRequested)
        {
            outcome = $"{e.GetType().Name} wrapping {e.InnerException?.GetType().Name}";
        }

        Assert.True(outcome == BudgetErrors.GateUnavailableType, $"expected {BudgetErrors.GateUnavailableType}, actual {outcome}");
    }

    private sealed class CancellingClock(CancellationTokenSource caller) : TimeProvider
    {
        public override ITimer CreateTimer(TimerCallback callback, object? state, TimeSpan dueTime, TimeSpan period)
        {
            caller.Cancel();
            throw new InvalidOperationException("the timer failed", new NpgsqlException("connection lost", new TimeoutException("the operation has timed out")));
        }
    }

    /// <summary>
    /// ULG48. A driver fault that arrives because the caller cancelled is not the store's: the write gate does not answer it <c>gate-unavailable</c> (as the event
    /// store does not answer it unreadable); the fault propagates with the connection and the turn given back, and the request is gone.
    /// </summary>
    [Fact]
    [SuppressMessage("Design", "CA1031:Do not catch general exception types", Justification = "The fact reports whatever escaped the gate.")]
    public async Task R11_71_ULG48_ADriverFaultRaisedByTheCallersCancellationIsNotGateUnavailable()
    {
        using var caller = new CancellationTokenSource();
        var gate = new PostgresAgentWriteGate(fixture.AppRoleDataSource, new CancellingClock(caller), TimeSpan.FromSeconds(5), 16, "gate_" + Guid.NewGuid().ToString("N"));
        string outcome;
        try
        {
            var result = await gate.EnterAsync(Typed.Agent("https://agents.example/ulg48"), caller.Token);
            if (result.TryGetValue(out var hold, out var error))
            {
                await hold!.DisposeAsync();
                outcome = "entered";
            }
            else
            {
                outcome = error!.Type;
            }
        }
        catch (Exception) when (!Ct.IsCancellationRequested)
        {
            outcome = "propagated";
        }

        Assert.True(outcome == "propagated", $"expected the fault to propagate for a cancelled caller, actual {outcome}");
    }

    /// <summary>
    /// ULG13, the revision gate and the flag raiser's gate. The same fault arrives through the driver's own logging path: a logger that throws a wrapped driver
    /// fault once. If the driver does not let a logger's exception out of its code, the fact says so and is not a probe of the gate (reported by Task 0b).
    /// </summary>
    [Theory]
    [InlineData("revision")]
    [InlineData("flag")]
    [SuppressMessage("Design", "CA1031:Do not catch general exception types", Justification = "The fact reports whatever escaped the gate.")]
    public async Task R11_71_ULG13_TheRevisionAndFlagGatesAnswerAWrappedDriverFault(string which)
    {
        using var loggers = new ThrowingOnceLoggerFactory();
        var builder = new NpgsqlDataSourceBuilder(fixture.AppRoleConnectionString);
        builder.UseLoggerFactory(loggers);
        var source = builder.Build();
        _cleanup.Add(source);
        await using (var warm = await source.OpenConnectionAsync(Ct)) { }

        var digest = "sha256:" + new string('a', 64);
        var schema = "gate_" + Guid.NewGuid().ToString("N");
        string outcome;
        string expected;
        try
        {
            loggers.Arm();
            if (which == "revision")
            {
                expected = IngestErrors.RevisionGateUnavailable().Type;
                outcome = Outcome(await new PostgresRevisionGate(source, schema).TryEnterAsync(digest, Ct));
            }
            else
            {
                expected = FlagErrors.RaiserGateUnavailable().Type;
                outcome = Outcome(await new PostgresFlagRaiserGate(source, schema).TryEnterAsync(digest, Ct));
            }
        }
        catch (Exception e) when (!Ct.IsCancellationRequested)
        {
            expected = which == "revision" ? IngestErrors.RevisionGateUnavailable().Type : FlagErrors.RaiserGateUnavailable().Type;
            outcome = $"{e.GetType().Name} wrapping {e.InnerException?.GetType().Name}";
        }

        Assert.True(outcome == expected, $"expected {expected}, actual {outcome}");
    }

    // ----- ULG42: the private flag store -----

    private static FlagDetail Detail(string eventId) => new(eventId, "01J00000000000000000000001", "https://agents.example/raiser", "a rationale", "salt" + eventId);

    /// <summary>
    /// ULG42. The private flag store classifies by the one predicate: with a starved pool, <c>AppendAsync</c> and <c>ReadAllAsync</c> return a failed
    /// <see cref="Result{T}"/> of type <c>curia/flag/detail-store-unavailable</c> whose detail is the exception's type name and never its message; a unique
    /// violation is still <c>Exists</c>.
    /// </summary>
    [Fact]
    [SuppressMessage("Design", "CA1031:Do not catch general exception types", Justification = "The fact reports whatever escaped the store.")]
    public async Task R11_71_ULG42_ThePrivateFlagStoreAnswersAPoolTimeoutAsItsTypedUnavailableResult()
    {
        var schema = await fixture.CreateIsolatedFlagDetailSchemaAsync(Ct);
        var starved = StarvedSource();
        await using var occupant = await starved.OpenConnectionAsync(Ct);
        var starvedStore = new PostgresFlagDetailStore(starved, schema);
        var healthy = new PostgresFlagDetailStore(fixture.AppRoleDataSource, schema);
        var problems = new List<string>();

        async Task Check(string name, Func<Task<string>> call)
        {
            try
            {
                var outcome = await call();
                if (outcome.Length > 0) problems.Add($"{name}: {outcome}");
            }
            catch (Exception e) when (!Ct.IsCancellationRequested)
            {
                problems.Add($"{name}: expected a failed Result, actual {e.GetType().Name} (the pool timeout) escaped");
            }
        }

        string Typed<T>(Result<T> result) =>
            result.TryGetValue(out _, out var error)
                ? "expected a failed Result, actual a success"
                : error!.Type != FlagDetailRules.Unavailable("x").Type ? $"expected {FlagDetailRules.Unavailable("x").Type}, actual {error.Type}"
                : error.Detail is null || error.Detail.Contains("pool", StringComparison.OrdinalIgnoreCase) || error.Detail.Contains("exhausted", StringComparison.OrdinalIgnoreCase)
                    ? $"the detail \"{error.Detail}\" is not the exception's type name"
                    : string.Empty;

        await Check("AppendAsync", async () => Typed(await starvedStore.AppendAsync(Detail("01J0000000000000000000ULG1"), Ct)));
        await Check("ReadAllAsync", async () => Typed(await starvedStore.ReadAllAsync(Ct)));

        // The unique violation is still a domain refusal.
        var first = await healthy.AppendAsync(Detail("01J0000000000000000000ULG2"), Ct);
        var second = await healthy.AppendAsync(Detail("01J0000000000000000000ULG2"), Ct);
        if (!first.TryGetValue(out _, out _)) problems.Add("a healthy first append was refused");
        var secondType = second.TryGetValue(out _, out var again) ? "a success" : again!.Type;
        if (secondType != FlagDetailRules.Exists("x").Type) problems.Add($"a second append of one event: expected {FlagDetailRules.Exists("x").Type}, actual {secondType}");

        Assert.True(problems.Count == 0, string.Join('\n', problems));
    }
}
