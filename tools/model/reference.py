def sanitise(text):
    """A lone surrogate is U+FFFD before it is tokenized (the Forum's tokenizer does the same); JSON files hold the result."""
    return "".join("�" if 0xD800 <= ord(ch) <= 0xDFFF else ch for ch in text)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--hf-dir", required=True, help="a snapshot of BAAI/bge-small-en-v1.5 (tokenizer files and model.safetensors) at the manifest's revision")
    parser.add_argument("--model-dir", required=True, help="the directory holding the deployed model.onnx and vocab.txt")
    parser.add_argument("--generated", type=int, default=2400, help="how many generated strings to write (at least 2000)")
    parser.add_argument("--disagreements", help="write the strings the slow and the fast tokenizer disagree on to this file")
    parser.add_argument("--no-torch", action="store_true", help="skip the PyTorch cross-check of the ONNX vectors")
    args = parser.parse_args()
    if args.generated < 2000:
        sys.exit("--generated must be at least 2000")

    import numpy as np
    import onnxruntime as ort
    import tokenizers
    import transformers
    from transformers import AutoTokenizer, BertTokenizer

    fast = AutoTokenizer.from_pretrained(args.hf_dir)
    try:
        slow = BertTokenizer.from_pretrained(args.hf_dir)
    except Exception as ex:  # noqa: BLE001 - the slow tokenizer is a second opinion only
        slow = None
        print("slow tokenizer unavailable:", type(ex).__name__, file=sys.stderr)

    options = ort.SessionOptions()
    options.intra_op_num_threads = 2
    options.inter_op_num_threads = 1
    session = ort.InferenceSession(str(Path(args.model_dir) / "model.onnx"), options, providers=["CPUExecutionProvider"])
    torch_model = None
    if not args.no_torch:
        import torch
        from transformers import AutoModel

        torch.set_num_threads(2)
        torch_model = AutoModel.from_pretrained(args.hf_dir).eval()

    def input_ids(text, role):
        return fast((PREFIX + text) if role == "query" else text, truncation=True, max_length=512)["input_ids"]

    def vector_onnx(ids):
        n = len(ids)
        out = session.run(None, {"input_ids": np.array([ids], dtype=np.int64), "attention_mask": np.ones((1, n), dtype=np.int64), "token_type_ids": np.zeros((1, n), dtype=np.int64)})[0]
        v = out[0, 0].astype(np.float64)
        return v / np.linalg.norm(v)

    def vector_torch(ids):
        import torch

        n = len(ids)
        with torch.no_grad():
            out = torch_model(input_ids=torch.tensor([ids]), attention_mask=torch.ones(1, n, dtype=torch.long), token_type_ids=torch.zeros(1, n, dtype=torch.long))
        v = out.last_hidden_state[0, 0].numpy().astype(np.float64)
        return v / np.linalg.norm(v)

    # --- the canaries
    canaries = []
    worst = 0.0
    for cid, role, text in canary_texts():
        ids = input_ids(text, role)
        entry = {"id": cid, "role": role, "text": text, "token_ids": ids}
        placeable = any(i != fast.unk_token_id for i in ids[1:-1])
        if not placeable:
            entry["vector"] = []
        else:
            v = vector_onnx(ids)
            if torch_model is not None:
                worst = max(worst, float(np.max(np.abs(v - vector_torch(ids)))))
            entry["vector"] = [np.format_float_positional(np.float32(x), unique=True) for x in v]
        canaries.append(entry)
    if torch_model is not None:
        print(f"max |torch - onnxruntime| per component over the canaries: {worst:.3e}")
        if worst > 1e-4:
            sys.exit("the reference has no authority: PyTorch and onnxruntime differ by more than 1e-4")

    # --- the parity file
    lines, disagreements = [], []
    strings = [("corpus", sanitise(t)) for _, t in corpus200()] + [("generated", sanitise(t)) for t in generated(args.generated, make_stability_probe(fast))]
    for source, text in strings:
        ids = fast(text, add_special_tokens=False)["input_ids"]
        if slow is not None and slow(text, add_special_tokens=False)["input_ids"] != ids:
            disagreements.append(text)
        lines.append(ascii_json({"text": text, "ids": ids, "source": source}))
    PARITY.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"wrote {len(lines)} parity strings to {PARITY.relative_to(ROOT)}; the slow and the fast tokenizer disagree on {len(disagreements)}")
    if args.disagreements:
        Path(args.disagreements).write_text("\n".join(ascii_json(t) for t in disagreements) + "\n", encoding="ascii")

    # --- the manifest
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    manifest.pop("canaries", None)
    manifest.pop("reference_tools", None)
    manifest.pop("generated_by", None)
    manifest["reference_tools"] = {
        "python": platform.python_version(),
        "transformers": transformers.__version__,
        "tokenizers": tokenizers.__version__,
        "onnxruntime": ort.__version__,
        "numpy": np.__version__,
    }
    if torch_model is not None:
        import torch

        manifest["reference_tools"]["torch"] = torch.__version__
    manifest["generated_by"] = "tools/model/reference.py (Hugging Face fast tokenizer; Python onnxruntime over the deployed model.onnx; never the C# adapter)"
    manifest["canaries"] = []
    head = json.dumps(manifest, ensure_ascii=True, indent=1)
    assert head.endswith('"canaries": []\n}'), "the manifest's last member must be the canaries"
    def canary_line(c):
        # The vector is written as numbers (the shortest float32 spelling of each component), not as strings, and one canary to a line.
        members = [ascii_json(c[k]) for k in ("id", "role", "text", "token_ids")]
        return '{"id":%s,"role":%s,"text":%s,"token_ids":%s,"vector":[%s]}' % (*members, ",".join(c["vector"]))

    body = ",\n".join("  " + canary_line(c) for c in canaries)
    MANIFEST.write_text(head[: -len("[]\n}")] + "[\n" + body + "\n ]\n}\n", encoding="ascii")
    print(f"wrote {len(canaries)} canaries to {MANIFEST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
