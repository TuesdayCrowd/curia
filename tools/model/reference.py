# Code points assigned in Unicode 15.0 whose general category differs in the tables of the .NET 10 runtime the Forum runs on (Rune.GetUnicodeCategory compared with Python 3.12's
# unicodedata over every code point: U+1171E, a non-spacing mark in 15.0 and a spacing mark since). They are kept out of the sample so that the file fails for no reason it cannot hold;
# non-property (i) of the entry says what the rest of the drift costs.
HOST_CATEGORY_DRIFT = {0x1171E}


def predicted_class(cp):
    """What BERT's text preparation does with a character, from Python's Unicode 15.0 data: 'gone', 'space', 'punct' or 'word'."""
    ch = chr(cp)
    cat = unicodedata.category(ch)
    if cp in (0, 0xFFFD):
        return "gone"
    if ch in "\t\n\r":
        return "space"
    if cat in ("Cc", "Cf", "Co", "Cs", "Mn"):
        return "gone"
    if cat in ("Zs", "Zl", "Zp"):
        return "space"
    if cat.startswith("P") or 33 <= cp <= 47 or 58 <= cp <= 64 or 91 <= cp <= 96 or 123 <= cp <= 126:
        return "punct"
    if (0x4E00 <= cp <= 0x9FFF or 0x3400 <= cp <= 0x4DBF or 0x20000 <= cp <= 0x2A6DF or 0x2A700 <= cp <= 0x2B73F or 0x2B740 <= cp <= 0x2B81F
            or 0x2B820 <= cp <= 0x2CEAF or 0xF900 <= cp <= 0xFAFF or 0x2F800 <= cp <= 0x2FA1F):
        return "punct"
    return "word"


def make_stability_probe(fast):
    """A function from a code point to whether the fast tokenizer treats it as Python's Unicode 15.0 data says (cached)."""
    plain = lambda s: fast(s, add_special_tokens=False)["input_ids"]  # noqa: E731
    ids_ab, ids_a_b, a_id, b_id = plain("ab"), plain("a b"), plain("a")[0], plain("b")[0]
    cache = {}

    def observed(cp):
        ids = plain("a" + chr(cp) + "b")
        if ids == ids_ab:
            return "gone"
        if ids == ids_a_b:
            return "space"
        if len(ids) == 3 and ids[0] == a_id and ids[2] == b_id:
            return "punct"
        return "word"

    def stable(cp):
        if cp not in cache:
            cache[cp] = cp not in HOST_CATEGORY_DRIFT and observed(cp) == predicted_class(cp)
        return cache[cp]

    return stable


def assigned_by_category():
    groups = {}
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        cat = unicodedata.category(chr(cp))
        if cat == "Cn":
            continue
        groups.setdefault(cat, []).append(cp)
    return groups


NONCHARACTERS = [0xFDD0, 0xFDEF, 0xFFFE, 0xFFFF, 0x1FFFE, 0x1FFFF, 0x2FFFE, 0x10FFFE, 0x10FFFF]
WHITE_SPACE = [0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x20, 0x85, 0xA0, 0x1680, 0x2000, 0x2003, 0x200A, 0x2028, 0x2029, 0x202F, 0x205F, 0x3000]


def generated(count, stable):
    rnd = random.Random(SEED + 1)
    groups = assigned_by_category()
    cats = sorted(groups)
    marks = [c for c in groups["Mn"] + groups["Me"] + groups["Mc"] if stable(c)]
    letters = [chr(c) for c in range(ord("a"), ord("z") + 1)]
    out = []

    def pick(pool):
        """A code point of <pool> on which the reference agrees with Python's data (a pool of tens of thousands is never exhausted)."""
        while True:
            cp = rnd.choice(pool)
            if stable(cp):
                return cp

    def any_cp():
        if rnd.random() < 0.04:
            return rnd.choice(NONCHARACTERS + [0x378])
        return pick(groups[rnd.choice(cats)])

    def piece():
        r = rnd.random()
        if r < 0.5:
            return chr(any_cp())
        if r < 0.8:
            return rnd.choice(letters)
        if r < 0.9:
            return " "
        return rnd.choice("!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~")

    for _ in range(count * 24 // 100):
        out.append("".join(piece() for _ in range(rnd.randint(1, 10))))
    for _ in range(count * 12 // 100):
        base = rnd.choice(letters) + (rnd.choice(letters) if rnd.random() < 0.5 else "")
        run = "".join(chr(rnd.choice(marks)) for _ in range(rnd.randint(1, 8)))
        out.append(rnd.choice(["", "x ", "see "]) + base + run + rnd.choice(["", " y", " end", chr(rnd.choice(marks))]))
    specials = SPECIALS + [s.lower() for s in SPECIALS] + ["[Cls]", "[sEp]", "[Mask]", "[CLS", "CLS]", "[ CLS ]", "[[CLS]]", "[CLS][SEP]"]
    for _ in range(count * 12 // 100):
        s = rnd.choice(specials)
        out.append(rnd.choice(["", "a", "word ", "x.", "(", "caf" + chr(0xE9)]) + s + rnd.choice(["", "b", " word", ".x", ")", chr(rnd.choice(marks))]))
    for _ in range(count * 8 // 100):
        w = "".join(rnd.choice(letters) for _ in range(rnd.randint(0, 6)))
        out.append(rnd.choice(["[", "[[", "[ ", "("]) + w + rnd.choice(["]", "]]", " ]", ")"]) + rnd.choice(["", " ", "!"]))
    for _ in range(count * 8 // 100):
        n = rnd.choice([95, 98, 99, 100, 101, 102, 105, 150])
        kind = rnd.random()
        if kind < 0.6:
            out.append("".join(rnd.choice(letters) for _ in range(n)))
        elif kind < 0.8:
            out.append("".join(rnd.choice(letters) for _ in range(n - 1)) + chr(rnd.choice(marks)))
        else:
            script = rnd.choice(["Ll", "Lo", "Lu"])
            out.append("".join(chr(pick(groups[script])) for _ in range(n)))
    for _ in range(count * 12 // 100):
        words = ["".join(rnd.choice(letters) for _ in range(rnd.randint(1, 8))) for _ in range(rnd.randint(2, 6))]
        out.append("".join(w + chr(rnd.choice(WHITE_SPACE)) for w in words))
    for _ in range(count * 8 // 100):
        a, b = rnd.choice(letters), rnd.choice(letters)
        out.append(a + chr(rnd.choice(NONCHARACTERS)) + chr(rnd.choice(marks)) + b + (chr(rnd.choice(NONCHARACTERS)) if rnd.random() < 0.5 else ""))
    cjk = [c for c in groups["Lo"] if stable(c)]
    for _ in range(count * 8 // 100):
        r = rnd.random()
        if r < 0.4:
            seq = [chr(rnd.choice(range(0x4E00, 0x9FFF))) for _ in range(rnd.randint(1, 5))]
        elif r < 0.7:
            seq = [chr(rnd.choice(range(0xAC00, 0xD7A3))) for _ in range(rnd.randint(1, 5))]
        else:
            seq = [chr(rnd.choice(range(0x1100, 0x1113))) + chr(rnd.choice(range(0x1161, 0x1176))) + chr(rnd.choice(range(0x11A8, 0x11C3))) for _ in range(rnd.randint(1, 4))]
        if rnd.random() < 0.5:
            seq.insert(rnd.randint(0, len(seq)), rnd.choice(letters))
        if rnd.random() < 0.3:
            seq.append(chr(rnd.choice(cjk)))
        out.append(rnd.choice(["", " ", "a "]).join(seq))
    while len(out) < count:
        out.append("".join(piece() for _ in range(rnd.randint(2, 14))))
    return out[:count]


